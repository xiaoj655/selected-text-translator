import { execFileSync } from 'node:child_process'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const temporaryDirectory = await mkdtemp(join(tmpdir(), 'selected-reader-prompt-'))
try {
  const generator = fileURLToPath(new URL('../../android/scripts/generate-model-contracts.mjs', import.meta.url))
  execFileSync(process.execPath, [generator, temporaryDirectory])
  const contracts = JSON.parse(await readFile(join(temporaryDirectory, 'model-contracts.json'), 'utf8'))
  const prompt = contracts.articleMeaning.messages[0].content
  const source = `// Generated by harmony/scripts/generate-reader-prompt.mjs.\nexport const READER_SYSTEM_PROMPT: string = ${JSON.stringify(prompt)}\n`
  const destination = new URL('../entry/src/main/ets/services/ReaderPrompt.ts', import.meta.url)
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8') !== source) {
      throw new Error('The HarmonyOS reader prompt differs from the Android article meaning contract.')
    }
  } else {
    await writeFile(destination, source)
  }
} finally {
  await rm(temporaryDirectory, { recursive: true, force: true })
}
