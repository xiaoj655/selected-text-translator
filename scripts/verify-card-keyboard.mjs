import assert from 'node:assert/strict'

export async function verifyCardKeyboard({
  worker, context, origin, selectText, requests, errors, holdGuideResponse,
}) {
  await worker.evaluate(async () => {
    await chrome.storage.sync.set({ model: 'test-generic', reading_mode: 'guide' })
  })
  const keyboardPage = await context.newPage()
  keyboardPage.on('pageerror', (error) => errors.push(error.message))
  await keyboardPage.goto(`${origin}/keyboard`)
  await keyboardPage.locator('#selected-reading-assistant').waitFor({ state: 'attached' })
  await keyboardPage.evaluate(() => {
    const buttonEl = document.createElement('button')
    buttonEl.id = 'host-keyboard-target'
    buttonEl.textContent = 'Continue reading'
    buttonEl.style.cssText = 'position:fixed;top:10px;left:10px;font:14px sans-serif!important'
    document.getElementById('selected-reading-assistant').insertAdjacentElement('afterend', buttonEl)
    globalThis.hostEscapeEvents = []
    document.addEventListener('keydown', (event) => {
      if (event.key === 'Escape') globalThis.hostEscapeEvents.push({ defaultPrevented: event.defaultPrevented })
    })
  })
  async function waitForCardFocus(selector) {
    await keyboardPage.waitForFunction((selector) => {
      const root = document.getElementById('selected-reading-assistant').shadowRoot
      return Boolean(root.activeElement?.matches(selector))
    }, selector)
  }
  const keyboardCallsBeforeOpen = requests.length
  const initialGuide = holdGuideResponse()
  await selectText('reluctant', '#sentence', 0, keyboardPage)
  await keyboardPage.locator('.stt-trigger').focus()
  await keyboardPage.keyboard.press('Enter')
  await keyboardPage.locator('.stt-loading').waitFor()
  await waitForCardFocus('.stt-tab[aria-pressed="true"]')
  await initialGuide.started
  await keyboardPage.keyboard.press('Enter')
  await keyboardPage.keyboard.press('Space')
  initialGuide.release()
  await keyboardPage.locator('.stt-hint').waitFor()
  await waitForCardFocus('.stt-tab[aria-pressed="true"]')
  assert.equal(requests.length, keyboardCallsBeforeOpen + 1)
  assert.equal(await keyboardPage.locator('.stt-answer').count(), 0)
  assert.equal(await keyboardPage.locator('.stt-trigger').getAttribute('aria-expanded'), 'true')
  assert.equal(await keyboardPage.locator('.stt-trigger').getAttribute('aria-controls'), 'stt-reading-card')
  await keyboardPage.getByRole('button', { name: '翻译', exact: true }).focus()
  await keyboardPage.keyboard.press('Space')
  await keyboardPage.locator('.stt-card-block--translation').waitFor()
  await waitForCardFocus('.stt-tab[aria-pressed="true"]')
  await keyboardPage.keyboard.press('Enter')
  assert.equal(requests.length, keyboardCallsBeforeOpen + 2)
  await keyboardPage.getByRole('button', { name: '引导理解', exact: true }).focus()
  await keyboardPage.keyboard.press('Enter')
  await keyboardPage.locator('.stt-hint').waitFor()
  await waitForCardFocus('.stt-tab[aria-pressed="true"]')
  assert.equal(requests.length, keyboardCallsBeforeOpen + 2)
  await keyboardPage.locator('.stt-next-hint').focus()
  await keyboardPage.keyboard.press('Enter')
  await waitForCardFocus('.stt-next-hint')
  assert.equal(await keyboardPage.locator('.stt-hint').count(), 2)
  assert.equal(await keyboardPage.locator('.stt-answer').count(), 0)
  await keyboardPage.keyboard.press('Space')
  await waitForCardFocus('.stt-reveal')
  assert.equal(await keyboardPage.locator('.stt-hint').count(), 3)
  await keyboardPage.keyboard.press('Enter')
  await waitForCardFocus('.stt-answer')
  await keyboardPage.locator('.stt-save').focus()
  await keyboardPage.keyboard.press('Space')
  await keyboardPage.getByRole('button', { name: '✓ 已收藏', exact: true }).waitFor()
  await waitForCardFocus('.stt-save')
  assert.equal(await keyboardPage.locator('.stt-save').evaluate((el) => el.disabled), false)
  const refreshedGuide = holdGuideResponse()
  await keyboardPage.locator('.stt-regenerate').focus()
  await keyboardPage.keyboard.press('Enter')
  await keyboardPage.locator('.stt-refresh-status').waitFor()
  await waitForCardFocus('.stt-regenerate')
  assert.equal(await keyboardPage.locator('.stt-regenerate').getAttribute('aria-disabled'), 'true')
  assert.equal(await keyboardPage.locator('.stt-regenerate').evaluate((el) => el.disabled), false)
  assert.equal(await keyboardPage.locator('.stt-answer').count(), 1)
  await refreshedGuide.started
  await keyboardPage.keyboard.press('Space')
  await keyboardPage.keyboard.press('Enter')
  refreshedGuide.release()
  await keyboardPage.locator('.stt-refresh-status').waitFor({ state: 'detached' })
  await waitForCardFocus('.stt-regenerate')
  assert.equal(requests.length, keyboardCallsBeforeOpen + 3)
  assert.equal(await keyboardPage.locator('.stt-hint').count(), 1)
  assert.equal(await keyboardPage.locator('.stt-answer').count(), 0)
  const contextGuide = holdGuideResponse()
  await keyboardPage.keyboard.press('Space')
  await keyboardPage.locator('.stt-refresh-status').waitFor()
  await keyboardPage.locator('.stt-context summary').focus()
  await keyboardPage.keyboard.press('Enter')
  await contextGuide.started
  contextGuide.release()
  await keyboardPage.locator('.stt-refresh-status').waitFor({ state: 'detached' })
  await waitForCardFocus('.stt-context summary')
  assert.equal(await keyboardPage.locator('.stt-context').getAttribute('open'), '')
  const lateGuide = holdGuideResponse()
  await keyboardPage.locator('.stt-regenerate').focus()
  await keyboardPage.keyboard.press('Enter')
  await keyboardPage.locator('.stt-refresh-status').waitFor()
  await keyboardPage.locator('.stt-context summary').focus()
  await keyboardPage.keyboard.press('Tab')
  assert.equal(await keyboardPage.evaluate(() => document.activeElement.id), 'host-keyboard-target')
  await lateGuide.started
  lateGuide.release()
  await keyboardPage.locator('.stt-refresh-status').waitFor({ state: 'detached' })
  assert.equal(await keyboardPage.evaluate(() => document.activeElement.id), 'host-keyboard-target')
  assert.equal(await keyboardPage.locator('.stt-answer').count(), 0)
  await keyboardPage.keyboard.press('Escape')
  assert.deepEqual(await keyboardPage.evaluate(() => hostEscapeEvents), [{ defaultPrevented: false }])
  assert.equal(await keyboardPage.locator('.stt-card').count(), 1)
  assert.equal(await keyboardPage.evaluate(() => document.activeElement.id), 'host-keyboard-target')
  await keyboardPage.locator('.stt-context summary').focus()
  await keyboardPage.keyboard.press('Escape')
  await keyboardPage.locator('.stt-card').waitFor({ state: 'detached' })
  await waitForCardFocus('.stt-trigger')
  assert.equal(await keyboardPage.locator('.stt-trigger').getAttribute('aria-expanded'), 'false')
  assert.deepEqual(await keyboardPage.evaluate(() => hostEscapeEvents), [{ defaultPrevented: false }])
  const keyboardCallsBeforeSpace = requests.length
  const spaceGuide = holdGuideResponse()
  await selectText('offer', '#sentence', 0, keyboardPage)
  await keyboardPage.locator('.stt-trigger').focus()
  await keyboardPage.keyboard.press('Space')
  await keyboardPage.locator('.stt-loading').waitFor()
  await waitForCardFocus('.stt-tab[aria-pressed="true"]')
  await spaceGuide.started
  spaceGuide.release()
  await keyboardPage.locator('.stt-hint').waitFor()
  await waitForCardFocus('.stt-tab[aria-pressed="true"]')
  assert.equal(requests.length, keyboardCallsBeforeSpace + 1)
  await keyboardPage.close()
}
